/**
 * 台股代號格式 —— **單一真相**(TS 與 SQL 共用同一個樣式字串)
 *
 * ══════════════════════════════════════════════════════════════════════════
 * 🔴 這個樣式原本散在【持股路徑八處】各寫一份:`priceCache` ×4、`/api/bars`、
 *    `/api/corp-events`、`/api/quote-batch`,外加 `importParse` 與三條 DB check。
 *    散開的結果是:輪 7 把 `/^\d{4}$/` 記成「已知界限、現在不擋」,
 *    六週後使用者買了 `00646` / `009816`,**沒有人動過那行程式,它自己過期了**。
 *
 * ⚠️ 散開還有一個更難看見的後果:**各處判準並不一致**,所以症狀各不相同。
 *      00646   DB 收 / 報價層擋  → 有持倉、沒市值(淨值少算)
 *      009816  DB 擋 / 報價層擋  → 交易根本寫不進去
 *      AU9901  DB 擋 / Yahoo 無資料 → 寫不進去,且就算寫進去也無價
 *    一句「舊樣式擋掉這三檔」會把三種不同的病合併成一種(我第一版就寫錯了,
 *    被 `tests/ticker-format.mjs` 的對照斷言抓出來)。
 *
 * ℹ️ 全庫另有約 18 處 `/^\d{4}$/`,過濾的是**研究覆蓋範圍**(`Pilot_Reports`
 *    檔名是 `XXXX_名稱.md`,只有 4 碼普通股):`parseReport` / `news-related` /
 *    `compare` / `watchlist` / 熱力圖成分股 / CI 腳本。**那些刻意不放寬** ——
 *    放寬會讓 ETF 代號連向不存在的 `/report/00646`。
 *    `tests/ticker-format.mjs` 把這條分界釘成檢查:那些檔案若被順手放寬,會紅。
 *    失效觸發條件:**若 `Pilot_Reports` 開始收錄非 4 碼標的**,重訪該分界。
 *
 * 🔴 所以界限要連【失效觸發條件】一起記:
 *    **「若出現非 4 碼代號」** —— 而不是只記「現在全是 4 碼所以不擋」。
 *    **沒有觸發條件的界限,會在沒人看的時候到期。**
 *
 * ── 放寬到什麼程度:逐項問「讀錯的後果是什麼」 ──────────────────────
 *
 * 實際存在的台股代號形狀:
 *   普通股 4 碼            2330
 *   特別股 4 碼 + 字母      2891A
 *   ETF   4~6 碼(有前導零) 0050 · 00646 · 009816
 *   槓反 ETF 數字 + L/R/B   00632R · 00715L
 *   黃金現貨 字母 + 數字    AU9901
 *   TDR / 權證 6 碼        910322
 *
 * → `^[0-9A-Z]{4,6}$`
 *
 * ⚠️ **不可以更寬。** 這個樣式同時是「別把代理變成任意 URL 轉發」的那道閘:
 *    字元集只有大寫英數 → 不可能含 `/` `.` `:` `?` `%`,長度上限 6
 *    → 無法改變主機或路徑,最壞只是對 Yahoo 問一個不存在的代號(404)。
 *    只要放進 `.` 或放寬長度,那個性質就沒了。
 *
 * ⚠️ **只收大寫。** 正規化在輸入端做(`importParse` 與手動表單都 `.toUpperCase()`),
 *    regex 保持大寫 → 儲存形式唯一。否則 `au9901` 與 `AU9901` 會變成兩檔。
 *
 * ⚠️ 不用「官方代碼表白名單」:`stockSuffix.json` 只有 1,975 檔普通股
 *    (TWSE ISIN 的 CFI `ES` 過濾),**連 `0050` 都不在裡面** —— 當白名單會擋掉全部 ETF。
 * ══════════════════════════════════════════════════════════════════════════
 */

/**
 * 樣式的【字串】形式。SQL 的 check constraint 必須逐字使用同一份 ——
 * `tests/ticker-format.mjs` 會讀 migration 檔比對,兩邊漂掉就紅。
 */
export const TICKER_PATTERN = "^[0-9A-Z]{4,6}$";

export const TICKER_RE = new RegExp(TICKER_PATTERN);

/** 🔴 用它,不要在呼叫端自己寫 regex。 */
export const isValidTicker = (s: unknown): boolean =>
  typeof s === "string" && TICKER_RE.test(s);

/**
 * ── 「可接受的代號」≠「要試 .TW / .TWO 後綴的代號」 ──────────────────
 *
 * 🔴 這兩件事必須分開。`/api/quote-batch` 是**混載通道**:同一個端點既載台股代號,
 *    也載 `GC=F`(黃金期貨)、`^TWOII`(櫃買指數)、`BDRY`(乾散貨海運 ETF,美股)。
 *    前兩者含 `=` `^`,本來就不會被 `TICKER_RE` 匹配;
 *    **但 `BDRY` 是 4 碼純英文,`^[0-9A-Z]{4,6}$` 會收**
 *    → 若拿 `isValidTicker` 當路由判準,`BDRY` 會被劫持去問 `BDRY.TW` / `BDRY.TWO`,
 *    兩個都 404,新聞頁的海運報價就從「有」變成「沒有」。
 *
 *    這正是放寬時該逐欄問的後果:放寬的是**接受範圍**,不是**路由範圍**。
 *
 * → 後綴判準另外收窄成「數字開頭」:`^[0-9]{4,6}[A-Z]?$`(再受 6 字元上限約束)
 *      2330 · 2891A · 0050 · 00646 · 009816 · 00632R · 910322  ✓
 *      BDRY · AAPL                                              ✗ 走原樣路徑
 *
 * ⚠️ 已知不涵蓋:`AU9901`(黃金現貨,字母開頭)走原樣路徑 → Yahoo 查無 → null。
 *    這是**正確的結果**,因為 Yahoo 兩種後綴對它都是 404(已實測),
 *    它屬於「尚未接上價格來源」而不是「路由錯誤」(證交所有官方公開價,是我們還沒接)。
 *    失效觸發條件:**若將來出現字母開頭、且 Yahoo 以 .TW/.TWO 查得到的代號**,
 *    這條判準要重訪。
 */
const TW_SUFFIX_RE = /^[0-9]{4,6}[A-Z]?$/;

export const isTwSuffixCandidate = (s: unknown): boolean =>
  isValidTicker(s) && TW_SUFFIX_RE.test(s as string);

/**
 * ── 第三道閘:語意閘 `isTwTicker` ────────────────────────────────────
 *
 * 到這裡總共有三個判準,**各自有不同的職責,不可互相代用**:
 *
 *   isValidTicker        存取閘   DB check / API 參數
 *                                 只保證「不會變成任意 URL 轉發」,不保證是台股
 *   isTwTicker           語意閘   匯入 / 手動新增持股
 *                                 「真的像台股代號」—— 寫進資料庫前的那道
 *   isTwSuffixCandidate  路由閘   /api/quote-batch 要不要試 .TW / .TWO
 *
 * 🔴 為什麼語意閘非有不可:放寬到 `^[0-9A-Z]{4,6}$` 之後,
 *    `TSMC`、`TOTAL`、`CASH`、`NULL` 全部都會通過存取閘。
 *    匯入來源是 Excel 複製,**表格下方的合計列就長這樣** ——
 *    那會靜默變成一筆「持股」,而不是被拒絕並具名。
 *    放寬存取範圍是對的,但不該順手放寬「什麼算一檔股票」。
 *    (原本 `import-parse` 有一條「TSMC → 拒絕」,放寬後變綠 —— 守衛沒了才發現。)
 *
 * 規則 = 數字開頭 ∪ 具名例外。台股字母開頭的代號目前只有黃金現貨。
 *
 * ⚠️ 失效觸發條件:**若出現其他字母開頭的台股代號**(匯入時會被拒絕並具名,
 *    不會靜默),把它加進 `TW_LETTER_LEADING` 並補一條測試。
 */
export const TW_LETTER_LEADING: readonly string[] = ["AU9901"]; // 黃金現貨(單位是「台兩」不是股)

export const isTwTicker = (s: unknown): boolean =>
  isTwSuffixCandidate(s) || (typeof s === "string" && TW_LETTER_LEADING.includes(s));

/**
 * ── 數量單位 ──────────────────────────────────────────────────────
 *
 * 🔴 不是每一檔的數量都是「股」。`AU9901` 是黃金現貨,單位是**台兩**。
 *    持倉表把 3 顯示成「3 股」是說了一件假話,而且是那種讀的人不會起疑的假話。
 *
 * 預設「股」,只有例外才列在這裡;顯示端**只在非預設時**附加單位,
 * 這樣常態的欄位不會多出一堆重複字樣。
 *
 * ⚠️ 失效觸發條件:**若再出現非「股」計價的標的**(ETN、其他現貨商品),
 *    加進這張表。漏了不會報錯,只會默默顯示錯的單位 —— 所以它配一條測試。
 */
export const TICKER_QTY_UNIT: Readonly<Record<string, string>> = {
  AU9901: "台兩",
};

export const DEFAULT_QTY_UNIT = "股";

export const qtyUnitOf = (ticker: string): string =>
  TICKER_QTY_UNIT[ticker] ?? DEFAULT_QTY_UNIT;
